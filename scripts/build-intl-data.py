#!/usr/bin/env python3
"""Build the v38 locale data blobs from ICU4X's compiled data.

`Intl` and local-time names read ICU4X data through the linked data provider
of `varta-intl`, not through baked statics: the generator
(`scripts/intl-data`, a standalone tool crate with its own lockfile) loads
every payload of ICU4X 2.4's compiled data (CLDR 49), serializes it in
postcard 1 form and writes one blob per service in the format of
`varta_common::intl_data` to `crates/varta-compiler/src/link/intl/`, with
the data versions and per-marker sizes in `intl.json`. The compiler embeds
the blobs and appends the segments of the services a module links as
passive data segments.

Steps:

1. `markers`: regenerate `scripts/intl-data/src/markers.rs` from the locked
   ICU4X data crates (their baked-data macros, with iteration) and the
   service table below;
2. build and run the generator (offline after the first fetch, locked);
3. record the generator's source fingerprint, so the compiler test
   `intl_data_matches_its_generator` fails while the blobs are stale.

`--check` only compares the fingerprint.
"""
import argparse
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOOL = ROOT / "scripts/intl-data"
MARKERS = TOOL / "src/markers.rs"
OUTPUT = ROOT / "crates/varta-compiler/src/link/intl"
METADATA = OUTPUT / "intl.json"
FNV_OFFSET = 0xCBF29CE484222325
FNV_PRIME = 0x100000001B3

# Data crates whose baked macros the generator includes, and the `icu::`
# module each one's macros name.
DATA_CRATES = (
    "icu_locale_data", "icu_time_data", "icu_calendar_data", "icu_decimal_data",
    "icu_plurals_data", "icu_list_data", "icu_collator_data", "icu_segmenter_data",
    "icu_casemap_data", "icu_datetime_data", "icu_experimental_data",
)

# Markers no ECMA-402 service reads.
EXCLUDED = re.compile(
    r"LocaleExemplarCharacters|TimezoneIdentifiersWindows|PersonNames|Transliterator"
    r"|experimental::displaynames::"  # superseded by icu_locale's names
)

# The service of a marker path (after `icu::`), first match wins.
SERVICES = (
    (r"^locale::provider::names::", "displaynames"),
    (r"^locale::", "locale"),
    (r"^time::", "zone"),
    (r"^datetime::provider::time_zones::", "zone"),
    (r"^datetime::|^calendar::", "datetime"),
    (r"^decimal::provider::DecimalCompact", "compact"),
    (r"^decimal::|^experimental::dimension::provider::percent::", "decimal"),
    (r"^plurals::", "plurals"),
    (r"^list::", "list"),
    (r"^collator::", "collator"),
    (r"^segmenter::", "segmenter"),
    (r"^casemap::", "casemap"),
    (r"^experimental::relativetime::", "relativetime"),
    (r"^experimental::dimension::provider::currency::", "currency"),
    (r"^experimental::duration::", "duration"),
    (r"^experimental::(dimension::provider::units|measure|units)::", "units"),
)


def registry_sources():
    """The source directory of every locked package of the tool."""
    metadata = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked",
         "--manifest-path", str(TOOL / "Cargo.toml")],
        check=True, capture_output=True, text=True).stdout)
    return {package["name"]: pathlib.Path(package["manifest_path"]).parent
            for package in metadata["packages"]}


def service(path):
    for pattern, name in SERVICES:
        if re.search(pattern, path):
            return name
    sys.exit(f"build-intl-data: no service for marker {path}")


def markers():
    sources = registry_sources()
    blocks = []
    exports = []
    for crate in DATA_CRATES:
        data = sources[crate] / "data"
        impls = []
        for file in sorted(data.glob("*.rs.data")):
            text = file.read_text()
            # Some files are unformatted token streams.
            macro = re.search(r"macro_rules\s*!\s*__(impl_[a-z0-9_]+)", text).group(1)
            path = re.search(r"DataProvider\s*<\s*icu\s*::\s*([A-Za-z0-9_:\s]+?)\s*>", text)
            path = re.sub(r"\s+", "", path.group(1))
            if EXCLUDED.search(path):
                continue
            # ICU4X 2.4's iteration arm of singleton markers names a
            # nonexistent `BtreeSet`; a singleton has the one root payload.
            singleton = "BtreeSet" in text
            impls.append(f"    {macro}!(Gen{'' if singleton else ', ITER'});")
            crate_path = re.sub(r"^locale::fallback::", "locale_fallback::", path)
            exports.append((service(path), "icu_" + crate_path, singleton))
        blocks.append(
            "const _: () = {\n"
            f"    #[allow(unused_imports)]\n    use {crate}::*;\n"
            + "\n".join(impls) + "\n};\n")
    exports.sort()
    lines = [
        "// @generated by scripts/build-intl-data.py from the locked ICU4X data crates.",
        "#![allow(clippy::all)]",
        "use crate::{Exporter, Gen, icu};",
        "",
        "#[allow(unused_imports)]",
        "use icu_locale_data::make_provider;",
        "make_provider!(Gen);",
        "",
        *blocks,
        "/// Export every marker into its service blob.",
        "pub(crate) fn export(exporter: &mut Exporter) {",
        *[f"    exporter.{'singleton' if singleton else 'marker'}::<{path}>(\"{name}\");"
          for name, path, singleton in exports],
        "}",
        "",
    ]
    MARKERS.write_text("\n".join(lines))
    print(f"build-intl-data: {len(exports)} markers in {MARKERS.relative_to(ROOT)}")


def source_files():
    files = [path for path in TOOL.rglob("*")
             if path.is_file() and "target" not in path.relative_to(TOOL).parts]
    files.append(ROOT / "scripts/build-intl-data.py")
    files.append(ROOT / "crates/varta-common/src/intl_data.rs")
    return sorted(path.relative_to(ROOT).as_posix() for path in files)


def fingerprint():
    """FNV-1a 64 over `path NUL content NUL` of the generator's sources."""
    value = FNV_OFFSET
    for name in source_files():
        for chunk in (name.encode(), b"\0", (ROOT / name).read_bytes(), b"\0"):
            for byte in chunk:
                value = ((value ^ byte) * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
    return f"{value:016x}"


def build():
    markers()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["cargo", "run", "--release", "--locked", "--manifest-path", str(TOOL / "Cargo.toml"),
         "--", str(OUTPUT)],
        check=True, cwd=TOOL)
    metadata = json.loads(METADATA.read_text())
    metadata["sourceFingerprint"] = fingerprint()
    METADATA.write_text(json.dumps(metadata, indent=2) + "\n")
    total = sum(blob["bytes"] for blob in metadata["services"].values())
    print(f"build-intl-data: wrote {len(metadata['services'])} blobs, {total} bytes")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="only verify the recorded source fingerprint")
    args = parser.parse_args()
    if args.check:
        recorded = json.loads(METADATA.read_text())["sourceFingerprint"]
        if recorded != fingerprint():
            sys.exit("build-intl-data: the locale data is stale; run scripts/build-intl-data.py")
        print("build-intl-data: fingerprint current")
        return
    build()


if __name__ == "__main__":
    main()
