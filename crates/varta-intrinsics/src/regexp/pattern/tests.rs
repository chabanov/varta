#[test]
fn case_table_matches_canonicalize() {
    for (classes, members, unicode) in [
        (UNIT_CLASSES, UNIT_MEMBERS, false),
        (UNICODE_CLASSES, UNICODE_MEMBERS, true),
    ] {
        let derived = case::derived_classes(unicode);
        assert_eq!(table(classes), derived);
        assert_eq!(members, case::derived_members(&derived).as_slice());
    }
    assert_eq!(FOLDING, case::derived_folding().as_slice());
    // Nothing above the table's limit has a case mapping.
    assert!(
        (CASED_LIMIT + 1..=MAX_CODE_POINT)
            .all(|ch| case::canonicalize(ch, true) == ch && case::canonicalize(ch, false) == ch)
    );
}

#[test]
fn construction_reports_v8_messages_over_utf16() {
    let message = |pattern: &[u16], flags: &str| {
        String::from_utf16_lossy(&construct(pattern, &utf16(flags)).unwrap_err())
    };
    assert_eq!(
        message(&utf16("a/("), "ig"),
        "Invalid regular expression: /a/(/gi: Unterminated group"
    );
    assert_eq!(
        message(&utf16("a"), "gg"),
        "Invalid flags supplied to RegExp constructor 'gg'"
    );
    assert_eq!(
        message(&utf16("a"), "uv"),
        "Invalid flags supplied to RegExp constructor 'uv'"
    );
    // A lone surrogate stays in the message and in `source`.
    let lone = [0xD800, u16::from(b'(')];
    let text = construct(&lone, &[]).unwrap_err();
    assert!(text.ends_with(&utf16("(/: Unterminated group")));
    assert!(text.windows(2).any(|pair| pair == lone));
    let built = construct(&[0xD800], &utf16("u")).unwrap();
    assert_eq!(built.source, [0xD800]);
    assert_eq!(built.compiled.groups, 0);
    let named = construct(&utf16("(?<y>\\d+)-(\\d+)"), &utf16("dg")).unwrap();
    assert_eq!(named.compiled.joined_names(), "y,");
    assert_eq!(named.flags.text(), "dg");
}

#[test]
fn sources_escape_slashes_and_line_terminators() {
    for (pattern, source) in [
        ("", "(?:)"),
        ("a/b", "a\\/b"),
        ("a\\/b", "a\\/b"),
        ("[/]", "[/]"),
        ("\n\\\n", "\\n\\n"),
        ("\u{2028}", "\\u2028"),
    ] {
        assert_eq!(escape_source(&utf16(pattern)), utf16(source), "{pattern}");
    }
}
