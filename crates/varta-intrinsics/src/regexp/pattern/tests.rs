//! The shared pattern compiler: the checked-in case tables equal their
//! derivation from Canonicalize, run-time construction reports V8's
//! messages over UTF-16 patterns, and `source` escaping. The compiler's
//! `regexp::tests` cover the grammar and programs through the same code.
extern crate std;

use super::case::{self, CASED_LIMIT};
use super::case_table::{FOLDING, UNICODE_CLASSES, UNICODE_MEMBERS, UNIT_CLASSES, UNIT_MEMBERS};
use super::property;
use super::set::MAX_CODE_POINT;
use super::*;
use alloc::{string::String, vec::Vec};
use std::fmt::Write as _;

fn utf16(text: &str) -> Vec<u16> {
    text.encode_utf16().collect()
}
fn table(classes: &[&[u32]]) -> Vec<Vec<u32>> {
    classes.iter().map(|class| class.to_vec()).collect()
}

/// The `case_table.rs` source for the current `core` Unicode tables.
fn case_table_source() -> String {
    let mut source = String::from(
        "//! Generated by `regenerate_case_table` (`regexp::pattern::tests`) from\n\
         //! Canonicalize (`varta_common::regexp::canonicalize`); do not edit.\n\
         //! `case_table_matches_canonicalize` keeps it equal to its derivation.\n\
         #![cfg_attr(rustfmt, rustfmt::skip)]\n",
    );
    for (name, unicode, doc) in [
        (
            "UNIT",
            false,
            "Canonicalize without `u` (toUppercase per code unit)",
        ),
        (
            "UNICODE",
            true,
            "Canonicalize with `u` or `v` (simple case folding)",
        ),
    ] {
        let _ = writeln!(
            source,
            "/// The equivalence classes of {doc} with more than one member,\n\
             /// by canonical value.\npub(super) const {name}_CLASSES: &[&[u32]] = &["
        );
        let classes = case::derived_classes(unicode);
        for class in &classes {
            let members: Vec<String> = class.iter().map(|ch| std::format!("0x{ch:X}")).collect();
            let _ = writeln!(source, "&[{}],", members.join(", "));
        }
        source.push_str("];\n");
        let _ = writeln!(
            source,
            "/// Every member of `{name}_CLASSES` with its class index, by member.\n\
             pub(super) const {name}_MEMBERS: &[(u32, u16)] = &["
        );
        for (member, class) in case::derived_members(&classes) {
            let _ = writeln!(source, "(0x{member:X}, {class}),");
        }
        source.push_str("];\n");
    }
    source.push_str(
        "/// Every code point whose simple case folding differs from itself, with\n\
         /// its folding, by code point.\npub(super) const FOLDING: &[(u32, u32)] = &[\n",
    );
    for (ch, canonical) in case::derived_folding() {
        let _ = writeln!(source, "(0x{ch:X}, 0x{canonical:X}),");
    }
    source.push_str("];\n");
    source
}

/// The `emoji_table.rs` source for `emoji_sequences.txt`.
fn emoji_table_source() -> String {
    let mut source = String::from(
        "//! Generated by `regenerate_emoji_table` (`regexp::pattern::tests`) from\n\
         //! `emoji_sequences.txt`; do not edit. `emoji_table_matches_its_source`\n\
         //! keeps it equal to the text.\n\
         #![cfg_attr(rustfmt, rustfmt::skip)]\n\
         /// Each emoji property of strings with its sequences, each as its\n\
         /// length followed by its code points.\n\
         pub(super) const PROPERTIES: &[(&str, &[u32])] = &[\n",
    );
    for name in property::EMOJI_PARTS {
        let _ = writeln!(source, "(\"{name}\", &[");
        for sequence in property::emoji_text(EMOJI_TEXT, name).unwrap() {
            let mut line = std::format!("{},", sequence.len());
            for code_point in sequence {
                let _ = write!(line, " 0x{code_point:X},");
            }
            let _ = writeln!(source, "{line}");
        }
        source.push_str("]),\n");
    }
    source.push_str("];\n");
    source
}
const EMOJI_TEXT: &str = include_str!("emoji_sequences.txt");

/// Rewrites `emoji_table.rs` from `emoji_sequences.txt`; run explicitly
/// (`--ignored`) after updating the text.
#[test]
#[ignore = "generator: rewrites emoji_table.rs"]
fn regenerate_emoji_table() {
    let path =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src/regexp/pattern/emoji_table.rs");
    std::fs::write(path, emoji_table_source()).unwrap();
}

#[test]
fn emoji_table_matches_its_source() {
    let path =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src/regexp/pattern/emoji_table.rs");
    assert_eq!(std::fs::read_to_string(path).unwrap(), emoji_table_source());
}

