//! Flat nonmoving mark/sweep: roots are compiler-provided immutable slices, no object graph.
use super::*;

pub(super) fn function(globals: Globals) -> Function {
    const ROOT_CURSOR: u32 = 0;
    const CURRENT: u32 = 1;
    const SIZE: u32 = 2;
    const PREVIOUS_FREE: u32 = 3;
    const HEAD: u32 = 4;
    const TAIL: u32 = 5;
    const LAST_PREVIOUS: u32 = 6;
    const PTR: u32 = 7;
    const AGAIN: u32 = 0;
    const DONE: u32 = 1;
    let mut function = Function::new([(PTR + 1, ValType::I32)]);
    instructions(
        &mut function,
        [
            I::I32Const(abi::STRING_ROOT_BASE as i32),
            I::LocalSet(ROOT_CURSOR),
            I::Block(BlockType::Empty),
            I::Loop(BlockType::Empty),
            I::LocalGet(ROOT_CURSOR),
            I::GlobalGet(globals.roots),
            I::I32GeU,
            I::BrIf(DONE),
            I::LocalGet(ROOT_CURSOR),
            I::I64Load(ROOT),
            I::I32WrapI64,
            I::LocalTee(PTR),
            I::I32Const((abi::OWNED_STRING_BASE + abi::STRING_HEADER_BYTES) as i32),
            I::I32GeU,
            I::If(BlockType::Empty),
            I::LocalGet(PTR),
            I::GlobalGet(globals.heap),
            I::I32GeU,
            I::If(BlockType::Empty),
            I::Unreachable,
            I::End,
            I::LocalGet(PTR),
            I::I32Const(HEADER as i32),
            I::I32Sub,
            I::LocalSet(CURRENT),
            I::LocalGet(CURRENT),
            I::I32Load(FLAG),
            I::I32Const(ALLOCATED),
            I::I32And,
            I::I32Eqz,
            I::If(BlockType::Empty),
            I::Unreachable,
            I::End,
            I::LocalGet(CURRENT),
            I::LocalGet(CURRENT),
            I::I32Load(FLAG),
            I::I32Const(MARKED),
            I::I32Or,
            I::I32Store(FLAG),
            I::End,
            I::LocalGet(ROOT_CURSOR),
            I::I32Const(abi::STRING_ROOT_SLOT_BYTES as i32),
            I::I32Add,
            I::LocalSet(ROOT_CURSOR),
            I::Br(AGAIN),
            I::End,
            I::End,
            I::I32Const(abi::OWNED_STRING_BASE as i32),
            I::LocalSet(CURRENT),
            I::Block(BlockType::Empty),
            I::Loop(BlockType::Empty),
            I::LocalGet(CURRENT),
            I::GlobalGet(globals.heap),
            I::I32GeU,
            I::BrIf(DONE),
            I::LocalGet(CURRENT),
            I::I32Load(WORD),
            I::LocalSet(SIZE),
            I::LocalGet(CURRENT),
            I::I32Load(FLAG),
            I::I32Const(MARKED),
            I::I32And,
            I::If(BlockType::Empty),
            I::LocalGet(CURRENT),
            I::I32Const(ALLOCATED),
            I::I32Store(FLAG),
            I::I32Const(0),
            I::LocalSet(PREVIOUS_FREE),
            I::Else,
            I::LocalGet(CURRENT),
            I::I32Const(0),
            I::I32Store(FLAG),
            I::LocalGet(PREVIOUS_FREE),
            I::If(BlockType::Empty),
            I::LocalGet(PREVIOUS_FREE),
            I::LocalGet(PREVIOUS_FREE),
            I::I32Load(WORD),
            I::LocalGet(SIZE),
            I::I32Add,
            I::I32Store(WORD),
            I::Else,
            I::LocalGet(TAIL),
            I::LocalSet(LAST_PREVIOUS),
            I::LocalGet(TAIL),
            I::I32Eqz,
            I::If(BlockType::Empty),
            I::LocalGet(CURRENT),
            I::LocalSet(HEAD),
            I::Else,
            I::LocalGet(TAIL),
            I::LocalGet(CURRENT),
            I::I32Store(LINK),
            I::End,
            I::LocalGet(CURRENT),
            I::LocalSet(TAIL),
            I::LocalGet(CURRENT),
            I::LocalSet(PREVIOUS_FREE),
            I::LocalGet(CURRENT),
            I::I32Const(0),
            I::I32Store(LINK),
            I::End,
            I::End,
            I::LocalGet(CURRENT),
            I::LocalGet(SIZE),
            I::I32Add,
            I::LocalSet(CURRENT),
            I::Br(AGAIN),
            I::End,
            I::End,
            // A dead trailing run can be removed from both heap and free list.
            I::LocalGet(PREVIOUS_FREE),
            I::If(BlockType::Empty),
            I::LocalGet(PREVIOUS_FREE),
            I::GlobalSet(globals.heap),
            I::LocalGet(LAST_PREVIOUS),
            I::I32Eqz,
            I::If(BlockType::Empty),
            I::I32Const(0),
            I::LocalSet(HEAD),
            I::Else,
            I::LocalGet(LAST_PREVIOUS),
            I::I32Const(0),
            I::I32Store(LINK),
            I::End,
            I::End,
            I::LocalGet(HEAD),
            I::GlobalSet(globals.free),
            I::End,
        ],
    );
    function
}
