//! First-fit reusable blocks; collect before growing committed memory, once per request.
use super::*;

pub(super) fn function(
    globals: Globals,
    collect: u32,
    limits: varta_common::limits::DataLimits,
) -> Function {
    use varta_common::limits::Resource;
    const LEN: u32 = 0;
    const NEED: u32 = 1;
    const CURRENT: u32 = 2;
    const PREVIOUS: u32 = 3;
    const SIZE: u32 = 4;
    const REST: u32 = 5;
    const REPLACEMENT: u32 = 6;
    const END: u32 = 7;
    const RETRIED: u32 = 8;
    const REPEAT: u32 = 0;
    const DONE: u32 = 1;
    const RETRY_FROM_IF: u32 = 1;
    let mut function = Function::new([(RETRIED, ValType::I32)]);
    let mut code = vec![
        I::LocalGet(LEN),
        I::I32Const(limits.allocation_bytes as i32),
        I::I32GtU,
        I::If(BlockType::Empty),
    ];
    code.extend(globals.fail(Resource::ValueSize, LEN));
    instructions(
        &mut function,
        code.into_iter()
            .chain([
                I::End,
                I::LocalGet(LEN),
                I::I32Const((HEADER + ALIGN - 1) as i32),
                I::I32Add,
                I::I32Const(-(ALIGN as i32)),
                I::I32And,
                I::LocalSet(NEED),
                I::Loop(BlockType::Empty),
                I::GlobalGet(globals.free),
                I::LocalSet(CURRENT),
                I::I32Const(0),
                I::LocalSet(PREVIOUS),
                I::Block(BlockType::Empty),
                I::Loop(BlockType::Empty),
                I::LocalGet(CURRENT),
                I::I32Eqz,
                I::BrIf(DONE),
                I::LocalGet(CURRENT),
                I::I32Load(WORD),
                I::LocalTee(SIZE),
                I::LocalGet(NEED),
                I::I32GeU,
                I::If(BlockType::Empty),
                I::LocalGet(SIZE),
                I::LocalGet(NEED),
                I::I32Sub,
                I::LocalTee(REST),
                I::I32Const((HEADER + ALIGN) as i32),
                I::I32GeU,
                I::If(BlockType::Empty),
                I::LocalGet(CURRENT),
                I::LocalGet(NEED),
                I::I32Add,
                I::LocalSet(REPLACEMENT),
                I::LocalGet(REPLACEMENT),
                I::LocalGet(REST),
                I::I32Store(WORD),
                I::LocalGet(REPLACEMENT),
                I::I32Const(0),
                I::I32Store(FLAG),
                I::LocalGet(REPLACEMENT),
                I::LocalGet(CURRENT),
                I::I32Load(LINK),
                I::I32Store(LINK),
                I::LocalGet(CURRENT),
                I::LocalGet(NEED),
                I::I32Store(WORD),
                I::Else,
                I::LocalGet(CURRENT),
                I::I32Load(LINK),
                I::LocalSet(REPLACEMENT),
                I::End,
                I::LocalGet(PREVIOUS),
                I::I32Eqz,
                I::If(BlockType::Empty),
                I::LocalGet(REPLACEMENT),
                I::GlobalSet(globals.free),
                I::Else,
                I::LocalGet(PREVIOUS),
                I::LocalGet(REPLACEMENT),
                I::I32Store(LINK),
                I::End,
                I::LocalGet(CURRENT),
                I::I32Const(ALLOCATED),
                I::I32Store(FLAG),
                I::LocalGet(CURRENT),
                I::I32Const(0),
                I::I32Store(LINK),
                I::LocalGet(CURRENT),
                I::I32Const(HEADER as i32),
                I::I32Add,
                I::Return,
                I::End,
                I::LocalGet(CURRENT),
                I::LocalSet(PREVIOUS),
                I::LocalGet(CURRENT),
                I::I32Load(LINK),
                I::LocalSet(CURRENT),
                I::Br(REPEAT),
                I::End,
                I::End,
                I::GlobalGet(globals.heap),
                I::LocalGet(NEED),
                I::I32Add,
                I::LocalSet(END),
                // Before increasing the memory high-water mark, trace all exact roots.
                I::LocalGet(END),
                I::MemorySize(MEMORY),
                I::I32Const(abi::WASM_PAGE_BYTES as i32),
                I::I32Mul,
                I::I32GtU,
                I::LocalGet(RETRIED),
                I::I32Eqz,
                I::I32And,
                I::If(BlockType::Empty),
                I::I32Const(1),
                I::LocalSet(RETRIED),
                I::Call(collect),
                I::Br(RETRY_FROM_IF),
                I::End,
                I::LocalGet(END),
                I::I32Const(abi::MAX_MEMORY_BYTES as i32),
                I::I32GtU,
                I::If(BlockType::Empty),
            ])
            .chain(globals.fail(Resource::Memory, NEED))
            .chain([
                I::End,
                I::LocalGet(END),
                I::MemorySize(MEMORY),
                I::I32Const(abi::WASM_PAGE_BYTES as i32),
                I::I32Mul,
                I::I32GtU,
                I::If(BlockType::Empty),
                I::LocalGet(END),
                I::I32Const((abi::WASM_PAGE_BYTES - 1) as i32),
                I::I32Add,
                I::I32Const(abi::WASM_PAGE_BYTES as i32),
                I::I32DivU,
                I::MemorySize(MEMORY),
                I::I32Sub,
                I::MemoryGrow(MEMORY),
                I::I32Const(-1),
                I::I32Eq,
                I::If(BlockType::Empty),
            ])
            .chain(globals.fail(Resource::Memory, NEED))
            .chain([
                I::End,
                I::End,
                I::GlobalGet(globals.heap),
                I::LocalTee(CURRENT),
                I::LocalGet(NEED),
                I::I32Store(WORD),
                I::LocalGet(CURRENT),
                I::I32Const(ALLOCATED),
                I::I32Store(FLAG),
                I::LocalGet(CURRENT),
                I::I32Const(0),
                I::I32Store(LINK),
                I::LocalGet(END),
                I::GlobalSet(globals.heap),
                I::LocalGet(CURRENT),
                I::I32Const(HEADER as i32),
                I::I32Add,
                I::Return,
                I::End,
                I::Unreachable,
                I::End,
            ]),
    );
    function
}
